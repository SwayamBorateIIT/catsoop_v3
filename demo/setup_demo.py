"""
Set up a local CAT-SOOP deployment with demo courses, users, and simulated
student submissions, for testing (e.g. the instructor analytics dashboard).

Usage:

    python demo/setup_demo.py            # write config (if missing), link
                                         # courses, create accounts, seed data
    python demo/setup_demo.py --clear    # remove everything this script added

The deployment uses its own configuration file (default
`~/.config/catsoop-desktop/config.py`), so any other CAT-SOOP configuration on
this machine is left untouched.  Start the server with `demo/start.sh`.

Every demo account has the password given by `--password` (default
`demo1234`).
"""

import os
import sys
import random
import hashlib
import secrets
import argparse
from datetime import datetime, timedelta

DEMO_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_DIR = os.path.dirname(DEMO_DIR)
COURSES_DIR = os.path.join(DEMO_DIR, "courses")

DEFAULT_CONFIG = os.path.expanduser("~/.config/catsoop-desktop/config.py")
DEFAULT_DATA_ROOT = os.path.expanduser("~/.local/share/catsoop")

CONFIG_TEMPLATE = """# CAT-SOOP configuration for the local demo deployment.
# Generated by demo/setup_demo.py; safe to edit.

cs_data_root = {data_root!r}
cs_auth_type = "login"
cs_allow_registration = False
cs_require_confirm_email = False

cs_url_root = "http://localhost:{port}"
cs_wsgi_server_port = {port}
cs_checker_server_port = {checker_port}
cs_checker_websocket = "ws://localhost:{checker_port}"
"""

# Simulated student behavior: (ability, number of released assignments the
# student keeps working on before dropping off; None = never drops off).
PROFILES = {
    "aarav": (0.95, None),
    "bella": (0.85, None),
    "chen": (0.75, None),
    "diego": (0.65, None),
    "emma": (0.9, None),
    "farah": (0.45, None),
    "george": (0.8, None),
    "hana": (0.55, 2),
    "ivan": (0.35, None),
    "julia": (0.7, 1),
    "kofi": (0.6, None),
    "lina": (0.0, 0),
    "mia": (0.5, None),
    "ta_lee": (0.85, None),
}


def demo_courses():
    return sorted(
        d
        for d in os.listdir(COURSES_DIR)
        if os.path.isfile(os.path.join(COURSES_DIR, d, "preload.py"))
    )


def read_users(course):
    out = {}
    udir = os.path.join(COURSES_DIR, course, "__USERS__")
    for fname in sorted(os.listdir(udir)):
        if fname.endswith(".py") and not fname.startswith(("_", ".")):
            info = {}
            with open(os.path.join(udir, fname)) as f:
                exec(f.read(), info)
            out[fname[:-3]] = {k: v for k, v in info.items() if k != "__builtins__"}
    return out


def ensure_config(config_path, data_root, port):
    if os.path.isfile(config_path):
        print("using existing config %s" % config_path)
        return
    os.makedirs(os.path.dirname(config_path), exist_ok=True)
    os.makedirs(data_root, exist_ok=True)
    with open(config_path, "w") as f:
        f.write(
            CONFIG_TEMPLATE.format(
                data_root=data_root, port=port, checker_port=port + 1
            )
        )
    print("wrote config %s" % config_path)


def load_catsoop(config_path):
    os.environ["CATSOOP_CONFIG"] = config_path
    if REPO_DIR not in sys.path:
        sys.path.insert(0, REPO_DIR)
    import catsoop.base_context as base_context

    if base_context._cs_config_errors:
        sys.exit("configuration errors:\n" + "\n".join(base_context._cs_config_errors))
    import catsoop.loader as loader

    return base_context, loader


def link_courses(data_root):
    cdir = os.path.join(data_root, "courses")
    os.makedirs(cdir, exist_ok=True)
    for course in demo_courses():
        src = os.path.join(COURSES_DIR, course)
        dst = os.path.join(cdir, course)
        if os.path.islink(dst) and os.path.realpath(dst) == os.path.realpath(src):
            print("course %s already linked" % course)
        elif os.path.lexists(dst):
            sys.exit("refusing to replace existing %s (not a demo link)" % dst)
        else:
            os.symlink(src, dst)
            print("linked course %s -> %s" % (dst, src))


def browser_hash(username, password):
    # matches catsoop_hash in catsoop/__AUTH__/login/__STATIC__/cs_hash.js,
    # which hashes the password in the browser before it is submitted
    return hashlib.pbkdf2_hmac(
        "sha256", password.encode(), (password + username).encode(), 100000, 32
    ).hex()


def create_accounts(context, users, password):
    login = context["csm_auth"].get_auth_type_by_name(context, "login")
    cslog = context["csm_cslog"]
    iterations = getattr(
        context["csm_base_context"], "cs_password_hash_iterations", 500000
    )
    for uname, info in sorted(users.items()):
        existing = cslog.most_recent("_logininfo", [], uname, None)
        if existing is not None and not existing.get("demo_account", False):
            print("  skipping %s: a non-demo account with that name exists" % uname)
            continue
        salt = login["get_new_password_salt"]()
        phash = login["compute_password_hash"](
            context, browser_hash(uname, password), salt, iterations
        )
        cslog.overwrite_log(
            "_logininfo",
            [],
            uname,
            {
                "password_salt": salt,
                "password_hash": phash,
                "email": "%s@demo.invalid" % uname,
                "name": info.get("name", uname),
                "confirmed": True,
                "demo_account": True,
            },
        )
    print("  %d accounts ready (password: %r)" % (len(users), password))


def assignment_dates(loader, path):
    ctx = loader.generate_context(path)
    tutor = ctx["csm_tutor"]
    return tutor.get_release_date(ctx), tutor.get_due_date(ctx)


def seed_course(context, loader, course, users):
    analytics = context["csm_analytics"]
    cslog = context["csm_cslog"]
    ctime = context["csm_time"]
    now = datetime.now()
    staff = sorted(u for u, i in users.items() if i.get("role") != "Student")
    grader = staff[-1] if staff else "None"
    assignments, errors = analytics.list_assignments(context, course, staff[0])
    for key, _ in errors:
        print("  warning: could not load page %s" % key)
    students = sorted(u for u, i in users.items() if i.get("role") == "Student")

    n_written = 0
    released_ix = -1
    for a in assignments:
        release, due = assignment_dates(loader, a["path"])
        if release > now:
            continue
        released_ix += 1
        in_progress = due > now
        for uname in students:
            ability, keep_going = PROFILES.get(uname, (0.6, None))
            rng = random.Random("%s:%s:%s" % (course, a["key"], uname))
            if keep_going is not None and released_ix >= keep_going:
                continue
            if in_progress and rng.random() > 0.6:
                continue
            state = {
                "scores": {},
                "last_submit": {},
                "last_submit_times": {},
                "nsubmits_used": {},
            }
            grades = []
            # weaker students are more likely to finish this assignment late
            late = not in_progress and rng.random() < 0.05 + 0.4 * (1 - ability)
            for name, q in a["questions"].items():
                if in_progress and rng.random() > 0.7:
                    continue
                if rng.random() > 0.8 + 0.2 * ability:
                    continue
                qrng = random.Random("%s:%s:%s" % (course, a["key"], name))
                difficulty = qrng.uniform(0.0, 0.25)
                if "hard" in str(q.get("csq_display_name", "")).lower():
                    difficulty += 0.35
                correct = rng.random() < max(0.05, ability - difficulty + 0.2)
                score = 1.0 if correct else rng.choice([0.0, 0.0, 0.5])
                if late and rng.random() < 0.7:
                    when = min(now, due + timedelta(hours=rng.uniform(1, 48)))
                else:
                    when = min(due, now) - timedelta(hours=rng.uniform(1, 96))
                stamp = ctime.detailed_timestamp(when)
                state["last_submit"][name] = "(demo submission)"
                state["last_submit_times"][name] = stamp
                state["nsubmits_used"][name] = (
                    rng.randint(1, 2) if correct else rng.randint(1, 5)
                )
                if q.get("csq_grading_mode") == "manual":
                    if rng.random() < 0.75:
                        grades.append(
                            {
                                "qname": name,
                                "grader": grader,
                                "score": round(
                                    min(1.0, ability + rng.uniform(-0.2, 0.2)), 2
                                ),
                                "comments": "Demo grade.",
                                "timestamp": stamp,
                            }
                        )
                else:
                    state["scores"][name] = score
            if not state["last_submit"]:
                continue
            state["timestamp"] = max(state["last_submit_times"].values())
            cslog.overwrite_log(uname, a["path"], "problemstate", state)
            cslog.delete_log(uname, a["path"], "problemgrades")
            for g in grades:
                cslog.update_log(uname, a["path"], "problemgrades", g)
            n_written += 1
    print(
        "  seeded %d submissions records across %d assignments"
        % (n_written, len(assignments))
    )


def clear_course(context, course, users):
    analytics = context["csm_analytics"]
    cslog = context["csm_cslog"]
    for path in analytics.list_pages(context, course):
        for uname in users:
            for log in ("problemstate", "problemgrades", "problemactions"):
                cslog.delete_log(uname, path, log)
    for uname in users:
        existing = cslog.most_recent("_logininfo", [], uname, None)
        if existing is not None and existing.get("demo_account", False):
            cslog.delete_log("_logininfo", [], uname)
    print("  cleared submissions and demo accounts")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--config", default=DEFAULT_CONFIG)
    parser.add_argument("--data-root", default=DEFAULT_DATA_ROOT)
    parser.add_argument("--port", type=int, default=7667)
    parser.add_argument("--password", default="demo1234")
    parser.add_argument(
        "--clear", action="store_true", help="remove demo data, accounts, links"
    )
    args = parser.parse_args()

    if args.clear and not os.path.isfile(args.config):
        sys.exit("no config at %s; nothing to clear" % args.config)
    if not args.clear:
        ensure_config(args.config, args.data_root, args.port)
    base_context, loader = load_catsoop(args.config)
    data_root = base_context.cs_data_root
    print("data root: %s" % data_root)

    if not args.clear:
        link_courses(data_root)
    context = loader.generate_context([])
    for course in demo_courses():
        users = read_users(course)
        print("%s:" % course)
        if args.clear:
            clear_course(context, course, users)
        else:
            create_accounts(context, users, args.password)
            seed_course(context, loader, course, users)
    if args.clear:
        for course in demo_courses():
            dst = os.path.join(data_root, "courses", course)
            if os.path.islink(dst):
                os.unlink(dst)
                print("unlinked %s" % dst)
    else:
        print("\ndone. start the server with:  demo/start.sh")


if __name__ == "__main__":
    main()
